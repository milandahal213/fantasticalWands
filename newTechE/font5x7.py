FIRST = 0x20
LAST = 0x7E
WIDTH = 6   # 5px glyph + 1px spacing
HEIGHT = 7


def char(fb, ch, x, y, color=1):
    """Draw one character; return the x advance (WIDTH)."""
    c = ord(ch)
    if c < FIRST or c > LAST:
        c = ord("?")
    base = (c - FIRST) * 5
    for col in range(5):
        bits = _FONT[base + col]
        cx = x + col
        for row in range(7):
            if bits & (1 << row):
                fb.pixel(cx, y + row, color)
    return WIDTH


def text(fb, string, x, y, color=1):
    """Draw a string at (x, y). No wrapping; caller manages lines."""
    cx = x
    for ch in string:
        cx += char(fb, ch, cx, y, color)
